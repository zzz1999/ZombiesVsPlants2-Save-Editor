    public static int Count => Definitions.Count;

    public static string DisplayName(BigInteger plantId) =>
        TryGet(plantId, out PlantDefinition? definition) && definition is not null
            ? definition.Name
            : "Unknown Plant";

    public static bool TryGet(BigInteger plantId, out PlantDefinition? definition)
    {
        if (plantId < int.MinValue || plantId > int.MaxValue)
        {
            definition = null;
            return false;
        }

        return Definitions.TryGetValue((int)plantId, out definition);
    }
